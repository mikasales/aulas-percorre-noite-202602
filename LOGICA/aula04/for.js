// Era uma vez os laços de repetição da lógica de programação e o laço for era o mais utilizado por economizar espaço e trazer praticidade para o desenvolvimento. Todos viveram felizes para sempre

//Para utilizar o for é necessário ter um contador para que delimitemos a quantidade de vezes que algo será repetido. A estrutura do for recebe inicialização, condição e incremento.

console.log("vou contar até 10 e depois dizer morango");


//  inicialização  condição   incremento
for(let i = 1;     i <= 10;   i += 2 ) {
    console.log(i);
}

console.log("Morango!!!");